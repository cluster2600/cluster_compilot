"""Imperfect-nest kernels (Track C): solvers whose statements live at DIFFERENT
loop depths, under a possibly loop-carried outer loop, with SIBLING inner loops.

PolyBench solvers (trisolv/lu/cholesky/ludcmp/durbin/gramschmidt, plus the
triangular BLAS trmm/symm and nussinov) are not perfect nests. cholesky, under
row i, runs a j-loop (itself holding a k-reduction then a divide) AND a separate
diagonal k-loop AND a scalar sqrt — three siblings at differing depths. So a
kernel here is an explicit list of statements, each tagged with its OWN enclosing
loop list; the loop tree keeps the common loop prefix of adjacent statements open
(two adjacent statements with identical loop tuples share the loop; give a loop a
different var name to force a sibling loop instead, as durbin's z/copy does).

Legality is EXACT, over all statements at once (union.UnionProgram): each
statement's domain comes from its loops, its accesses are read from its C body
(flat subscripts with the sizes substituted; accesses under a condition count
unconditionally, which can only add dependences), and the loop tree becomes a
2d+1 schedule. Scalars declared in the kernel's `setup` are 0-d arrays (shared
by everything); a scalar a statement declares (`double w = ...`) is expanded over
that statement's loops — exactly its C scope, so it is private per iteration of
its innermost loop and shared by the deeper statements that use it.

Execution supports parallel(L): every loop named L must carry no dependence
between instances inside it. Scheduled code is generated by ISL from the 2d+1
schedule (union.to_c, which also declares those scalars in their original
scope); the baseline is the plain loop tree below, so the checksum comparison
stays an independent check. Other transforms report "unsupported".
"""
import re
import threading
from dataclasses import dataclass, field

import islpy as isl

from . import codegen as _cg
from . import runner as _runner
from . import schedule as _schedule
from . import union as _union
from .backend_isl import SCHEDULE_ERRORS, Result
from .polyhedral import ISL_LOCK, dependences

_EXECUTABLE = {"parallel"}        # transforms the imperfect codegen can emit
_DECL = re.compile(r"\b(double|float|int|long)\s+([A-Za-z_]\w*)\s*=")


@dataclass
class IStmt:
    loops: list      # enclosing loops outermost-first: (var, lo, hi) asc, or (var, lo, hi, "rev") desc
    body: str        # raw C with explicit flat indexing


@dataclass
class ImperfectKernel:
    name: str
    sizes: dict
    arrays: dict                 # name -> tuple of dims (any rank)
    statements: list             # [IStmt] in program order
    final: str                   # checksum array
    reset: dict = field(default_factory=dict)   # array -> "zero" | "reinit" (per rep)
    setup: str = ""              # C run each rep before timing (scalar decls, diagonal boost)


def union_program(ik):
    """The exact union model of `ik` at its concrete sizes (see module docstring)."""
    stmts_in = ik.statements
    times = _union.tree_times([st.loops for st in stmts_in])
    shared = set(_union.setup_scalars(ik.setup))
    decl_sites = [(k, name) for k, st in enumerate(stmts_in) for _, name in _DECL.findall(st.body)]
    sub = lambda e: _union._subst(str(e), ik.sizes)
    out = []
    for k, st in enumerate(stmts_in):
        def scalar_ref(name, k=k, st=st):
            # the latest declaration of `name` whose scope (its loop prefix, the same
            # loop instances) encloses statement k
            for s, nm in reversed(decl_sites):
                if nm != name or s > k:
                    continue
                d = len(stmts_in[s].loops)
                if (tuple(map(tuple, st.loops[:d])) == tuple(map(tuple, stmts_in[s].loops))
                        and _union.betas(times[s], d - 1) == _union.betas(times[k], d - 1)):
                    return (f"{name}__s{s}", ",".join(lv[0] for lv in stmts_in[s].loops))
            return (name, "") if name in shared else None
        reads, writes = _union.body_accesses(st.body, ik.arrays, ik.sizes, scalar_ref)
        decls = [(ctype, name) for ctype, name in _DECL.findall(st.body)]
        body = _DECL.sub(lambda m: f"{m.group(2)} =", st.body)     # declared where it's scoped
        dom = " and ".join(f"{sub(lv[1])} <= {lv[0]} < {sub(lv[2])}" for lv in st.loops)
        out.append(_union.UStmt(f"S{k}", [lv[0] for lv in st.loops], dom, reads, writes, body,
                                times[k], [lv[0] for lv in st.loops], decls))
    return _union.UnionProgram(out)


def _emit_nest(statements, parallel_vars, base):
    """Walk statements, keeping the common loop prefix open (tree codegen).

    A parallel loop gets a `#pragma omp parallel for` at each of its occurrences.
    Per-occurrence fork/join (not a hoisted region) — always correct regardless of
    sibling statements; the solver family doesn't win from parallelism anyway, so
    correctness + legality is the deliverable, not work-share overhead.
    """
    ind = lambda n: base + "  " * n
    lines, open_loops = [], []
    for st in statements:
        cp = 0
        while (cp < len(open_loops) and cp < len(st.loops)
               and tuple(open_loops[cp]) == tuple(st.loops[cp])):
            cp += 1
        while len(open_loops) > cp:                       # close diverged loops
            open_loops.pop()
            lines.append(ind(len(open_loops)) + "}")
        for lv in st.loops[cp:]:                          # open this statement's new loops
            n = len(open_loops)
            var, lo, hi = lv[0], lv[1], lv[2]
            rev = len(lv) > 3 and lv[3] == "rev"
            if var in parallel_vars:
                lines.append(ind(n) + "#pragma omp parallel for")
            if rev:
                lines.append(ind(n) + f"for(int {var}=({hi})-1;{var}>=({lo});{var}--){{")
            else:
                lines.append(ind(n) + f"for(int {var}={lo};{var}<{hi};{var}++){{")
            open_loops.append(lv)
        lines.append(ind(len(open_loops)) + st.body)
    while open_loops:
        open_loops.pop()
        lines.append(ind(len(open_loops)) + "}")
    return "\n".join(lines)


def _emit(ik, nest=None):
    """Timed program for `ik`: `nest` is a scheduled nest (union.to_c), or None for
    the plain loop tree (the baseline)."""
    tot = lambda a: "*".join(str(x) for x in ik.arrays[a])
    pat = "(double)((f_*13+7)%97)/97.0"
    sizes = "\n".join(f"  const int {k} = {v};" for k, v in ik.sizes.items())
    allocs = "\n".join(f"  double *{a} = malloc((size_t)({tot(a)})*sizeof(double));" for a in ik.arrays)
    inits = "\n".join(f"  for (long f_=0;f_<(long)({tot(a)});f_++) {a}[f_]={pat};"
                      for a in ik.arrays if a not in ik.reset)
    resets = "\n".join(
        f"    for (long f_=0;f_<(long)({tot(a)});f_++) {a}[f_]={pat if m == 'reinit' else '0.0'};"
        for a, m in ik.reset.items())
    setup = f"    {ik.setup}" if ik.setup else ""
    nest = _emit_nest(ik.statements, set(), "    ") if nest is None else nest
    # position-weighted (f_+1): an unweighted sum is permutation-invariant and would
    # miss a transposed/mirrored write that lands the right values in the wrong cells.
    checksum = f"  double acc_=0; for(long f_=0;f_<(long)({tot(ik.final)});f_++) acc_+=(double)(f_+1)*{ik.final}[f_];"
    return f"""#include <stdio.h>
#include <stdlib.h>
#include <time.h>
#include <math.h>
#ifdef _OPENMP
#include <omp.h>
#endif
{_cg.PRELUDE}
#define MAX(a,b) ((a)>(b)?(a):(b))
int main(void){{
{sizes}
{allocs}
{inits}
  double best=1e30;
  for(int rep=0;rep<3;rep++){{
{resets}
{setup}
    struct timespec t0,t1; clock_gettime(CLOCK_MONOTONIC,&t0);
{nest}
    clock_gettime(CLOCK_MONOTONIC,&t1);
    double dt=(t1.tv_sec-t0.tv_sec)+(t1.tv_nsec-t0.tv_nsec)*1e-9;
    if(dt<best)best=dt;
  }}
{checksum}
  printf("TIME %.9f\\nCHECKSUM %.6e\\n", best, acc_);
{_cg.THREADS}
  return 0;
}}
"""


class ImperfectEnvironment:
    """Single shared schedule over an imperfect nest. Exposes .baseline()/.evaluate()/
    .confirm()/.render() so the single-statement agent dialogue, prompt builder, and
    MCP/TUI single-schedule paths work unchanged."""

    def __init__(self, ik):
        self.ik = ik
        with ISL_LOCK:
            self.prog = union_program(ik)
            self.D = dependences(self.prog)
            self.theta = self.prog.schedule()
        self.times = [s.time for s in self.prog.stmts]
        self._baseline = None
        self._baseline_lock = threading.Lock()

    def render(self):
        """The original loop tree, as shown to the LLM."""
        return _emit_nest(self.ik.statements, set(), "")

    def baseline_program(self):
        return _emit(self.ik)

    def baseline(self):
        if self._baseline is None:
            with self._baseline_lock:
                if self._baseline is None:
                    r = _runner.compile_and_run(self.baseline_program())
                    if not r["ok"]:
                        raise RuntimeError(f"baseline failed: {r}")
                    self._baseline = r
        return self._baseline

    def loops_named(self, label):
        """(depth, betas) of every distinct loop whose variable is `label`."""
        return sorted({(p, _union.betas(t, p)) for s, t in zip(self.prog.stmts, self.times)
                       for p, lbl in enumerate(s.labels) if lbl == label})

    def _check(self, schedule_text):
        """Exact union legality. Returns (program, None) or (None, Result)."""
        try:
            ops = _schedule.parse(schedule_text)
        except SCHEDULE_ERRORS as e:
            return None, Result("invalid", detail=str(e), schedule=schedule_text)
        used = {op for op, _ in ops}
        if not used <= _EXECUTABLE:
            return None, Result("unsupported",
                                detail=f"imperfect-nest kernels execute parallel() only, not "
                                       f"{sorted(used - _EXECUTABLE)}", schedule=schedule_text)
        pragmas = {}
        with ISL_LOCK:                    # see polyhedral.ISL_LOCK
            for _, args in ops:
                loops = self.loops_named(args[0]) if args else []
                if not loops:
                    return None, Result("invalid", detail=f"no loop named {args[0] if args else '?'!r}",
                                        schedule=schedule_text)
                for p, key in loops:
                    if not _union.loop_is_parallel(self.prog, self.D, self.theta, self.times, p, key):
                        return None, Result("parallel_illegal",
                                            detail=f"loop {args[0]} (depth {p}) carries a dependence; "
                                                   f"cannot parallelize", schedule=schedule_text)
                    pragmas[(p, key)] = ["#pragma omp parallel for"]
            nest = _union.to_c(self.prog, self.theta, self.times, isl.Set("{ : }"), pragmas)
        return _emit(self.ik, nest), None

    def evaluate(self, schedule_text) -> Result:
        program, failed = self._check(schedule_text)
        if failed:
            return failed
        base = self.baseline()
        r = _runner.compile_and_run(program)
        if not r["ok"]:
            return Result(r["error"], detail=r.get("detail", ""), schedule=schedule_text)
        ref = base["checksum"]
        if not _runner.checksums_match(r["checksum"], ref):
            return Result("incorrect", detail=f"checksum {r['checksum']:.6e} != baseline {ref:.6e}",
                          schedule=schedule_text)
        return Result("success", speedup=base["time"] / r["time"],
                      detail=f"{base['time']:.4f}s -> {r['time']:.4f}s", schedule=schedule_text)

    def confirm(self, schedule_text, rounds=_runner.CONFIRM_ROUNDS, interleaved=False):
        """Re-measured speedup (see runner.confirm_speedup), or None."""
        program, failed = self._check(schedule_text)
        if failed:
            return None
        return _runner.confirm_speedup(self.baseline(), self.baseline_program(), program,
                                       rounds, interleaved)
