"""Turn (kernel, schedule) into a self-contained, timed C program.

Two emitters, deliberately independent:
  - the ORIGINAL nest is printed straight from the execution spec's loop list
    (the baseline, and the nest shown to the LLM);
  - a SCHEDULED nest is generated by ISL's AST generator from the very schedule
    map θ' that the legality engine proved (isl_nest), so the executed loop
    order is exactly the proven one — no second hand-written transform engine
    that could drift from the legality model.
The runner then compares the scheduled program's checksum against the baseline's,
which also catches any mismatch between the polyhedral spec and the C body.
"""
import re

import islpy as isl

from . import schedule as _schedule

REPS = 3  # timing repetitions; report the best

# Helpers ISL's C printer emits (min/max/floord), plus MIN used by kernel bodies.
PRELUDE = """#define MIN(a,b) ((a) < (b) ? (a) : (b))
#define min(a,b) ((a) < (b) ? (a) : (b))
#define max(a,b) ((a) > (b) ? (a) : (b))
#define floord(n,d) (((n) < 0) ? -((-(n) + (d) - 1) / (d)) : (n) / (d))
#define ceild(n,d) (((n) < 0) ? -((-(n)) / (d)) : ((n) + (d) - 1) / (d))"""

# Printed after TIME/CHECKSUM by every generated program; runner records it so a
# measurement says how many threads it ran with.
THREADS = """#ifdef _OPENMP
  printf("THREADS %d\\n", omp_get_max_threads());
#endif"""


def _loop_lohi(entry):
    """A loop entry is (var, hi) [lo=0] or (var, lo, hi)."""
    if len(entry) == 3:
        return entry[0], entry[1], entry[2]
    return entry[0], "0", entry[1]


def original_nest(loops, body, indent="    "):
    """The untransformed nest, printed from the execution spec's loop list."""
    out, pad = [], indent
    for entry in loops:
        v, lo, hi = _loop_lohi(entry)
        out.append(pad + f"for (int {v} = {lo}; {v} < {hi}; {v} += 1) {{")
        pad += "    "
    out.append(pad + body)
    for _ in loops:
        pad = pad[:-4]
        out.append(pad + "}")
    return "\n".join(out)


def render_nest(kernel):
    """Human-readable view of the original loop nest (for presenting to the LLM)."""
    return original_nest(kernel.loops, kernel.body, indent="")


_FOR = re.compile(r"^(\s*)for \(int c(\d+) ")


def isl_nest(poly, sizes, body, theta, parallel_levels=(), unroll_levels=(), indent="    "):
    """C for the statement `body` scheduled by θ' (from scheduler.build_theta).

    Callers hold polyhedral.ISL_LOCK (this builds ISL objects). Loops are named
    c<d> after schedule dimension d, so parallel()/unroll() pragmas go on every
    loop ISL emits for that dimension. The statement is a macro binding the
    original iterator names, so `body` is used verbatim.
    """
    if not theta.is_injective():
        raise ValueError("schedule maps distinct iterations to the same time step")
    p = ",".join(poly.params)
    eqs = " and ".join(f"{k} = {sizes[k]}" for k in poly.params)
    ctx = isl.Set(f"[{p}] -> {{ : {eqs} }}") if poly.params else isl.Set("{ : }")
    code = isl.AstBuild.from_context(ctx).node_from_schedule_map(theta).to_C_str()

    pragmas = {}
    for _, lvl in parallel_levels:
        pragmas.setdefault(lvl, []).append("#pragma omp parallel for")
    for _, lvl, f in unroll_levels:
        pragmas.setdefault(lvl, []).append(f"#pragma clang loop unroll_count({f})")
    lines = []
    for line in code.rstrip().splitlines():
        m = _FOR.match(line)
        if m:
            lines.extend(m.group(1) + pr for pr in pragmas.get(int(m.group(2)), ()))
        lines.append(line)

    args = [f"a{n}_" for n in range(len(poly.order))]
    binds = " ".join(f"const int {v} = ({a});" for v, a in zip(poly.order, args))
    return "\n".join([f"#define S({', '.join(args)}) do {{ {binds} {body} }} while (0)",
                      *(indent + ln for ln in lines),
                      "#undef S"])


def scheduled_nest(poly, sizes, body, schedule_text, indent="    "):
    """Parse + build θ' + generate (no legality check). Caller holds ISL_LOCK."""
    from .scheduler import build_theta
    theta, _, par, unroll = build_theta(poly, _schedule.parse(schedule_text))
    return isl_nest(poly, sizes, body, theta, par, unroll, indent)


def program(kernel, nest):
    """Wrap a loop nest for `kernel` in a timed main() that prints TIME/CHECKSUM."""
    sizes = "\n".join(f"  const int {k} = {v};" for k, v in kernel.sizes.items())
    allocs = "\n".join(
        f"  double *{a} = malloc((size_t){d[0]} * {d[1]} * sizeof(double));"
        for a, d in kernel.arrays.items()
    )
    # deterministic init for every input array (the output gets zeroed per rep)
    inits = []
    for a, (d0, d1) in kernel.arrays.items():
        if a == kernel.output:
            continue
        inits.append(
            f"  for (int x = 0; x < {d0}; x++) for (int y = 0; y < {d1}; y++) "
            f"{a}[x*{d1} + y] = (double)(((x*7 + y*13) % 97)) / 97.0;"
        )
    inits = "\n".join(inits)
    od0, od1 = kernel.arrays[kernel.output]
    rhs = ("(double)(((x*7 + y*13) % 97)) / 97.0" if kernel.reset == "reinit" else "0.0")
    zero = (f"    for (int x = 0; x < {od0}; x++) for (int y = 0; y < {od1}; y++) "
            f"{kernel.output}[x*{od1} + y] = {rhs};")
    # position-weighted: an unweighted sum is permutation-invariant, so a transposed/
    # mirrored write that hits the right *values* in the wrong *cells* would pass.
    checksum = (f"  double sum = 0.0;\n"
                f"  for (int x = 0; x < {od0}; x++) for (int y = 0; y < {od1}; y++) "
                f"sum += (x*{od1} + y + 1) * {kernel.output}[x*{od1} + y];")
    frees = "\n".join(f"  free({a});" for a in kernel.arrays)

    return f"""#include <stdio.h>
#include <stdlib.h>
#include <time.h>
#include <math.h>
#ifdef _OPENMP
#include <omp.h>
#endif
{PRELUDE}

int main(void) {{
{sizes}
{allocs}
{inits}
  double best = 1e30;
  for (int rep = 0; rep < {REPS}; rep++) {{
{zero}
    struct timespec t0, t1;
    clock_gettime(CLOCK_MONOTONIC, &t0);
{nest}
    clock_gettime(CLOCK_MONOTONIC, &t1);
    double dt = (t1.tv_sec - t0.tv_sec) + (t1.tv_nsec - t0.tv_nsec) * 1e-9;
    if (dt < best) best = dt;
  }}
{checksum}
  printf("TIME %.9f\\nCHECKSUM %.6e\\n", best, sum);
{THREADS}
{frees}
  return 0;
}}
"""


def generate_c(kernel, schedule_text="", poly=None):
    """Full program for `kernel`: the original nest, or (with `poly`, the paired
    PolyKernel) the ISL-generated nest for `schedule_text`."""
    if not schedule_text.strip():
        return program(kernel, original_nest(kernel.loops, kernel.body))
    if poly is None:
        raise ValueError("a scheduled program needs the kernel's PolyKernel (poly=...)")
    from .polyhedral import ISL_LOCK
    with ISL_LOCK:
        nest = scheduled_nest(poly, kernel.sizes, kernel.body, schedule_text)
    return program(kernel, nest)
